using System.Text;
using Dashboard.Core.Contracts;
using Dashboard.Core.Entities;
using Dashboard.Web.Audit;
using Dashboard.Web.Data;
using Microsoft.EntityFrameworkCore;

namespace Dashboard.Web.Services;

/// <summary>Weekly digest (deterministic Markdown) and an optional LLM brief written from week-over-week deltas only.</summary>
public sealed class WeeklyService(IServiceScopeFactory scopes, HealthService health, InsightsService insights, FindingsService findings, AuditorClient auditor, ConfigService config, IClock clock)
{
    public async Task<string> DigestAsync(CancellationToken ct = default)
    {
        var now = clock.UtcNow;
        var all = await health.GetAllAsync(ct);
        await using var scope = scopes.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<DashboardDbContext>();
        var ids = all.Select(h => h.Repo.Id).ToList();
        var weekAgo = now.AddDays(-7);
        var merged = await db.PullRequests.AsNoTracking().CountAsync(p => ids.Contains(p.RepoId) && p.Status == "completed" && p.ClosedOn >= weekAgo, ct);
        var prod = await db.Deployments.AsNoTracking().Where(d => ids.Contains(d.RepoId) && d.Tier == Dashboard.Core.Configuration.EnvironmentTier.Production && d.FinishTime >= weekAgo && d.Result == "succeeded")
            .Select(d => new { d.RunId, d.EnvironmentName }).Distinct().CountAsync(ct);
        var ins = await insights.BuildAsync(ct);
        var backlog = await findings.BacklogAsync();

        var sb = new StringBuilder();
        sb.AppendLine($"# Weekly digest — week ending {config.WorkingHours.ToLocal(now):ddd dd MMM yyyy}").AppendLine();
        sb.AppendLine($"- **{merged}** PRs merged, **{prod}** Production deployments (sim + prod)");
        sb.AppendLine($"- Tiers: {string.Join(", ", new[] { "Gold", "Silver", "Bronze", "None" }.Select(t => $"{t} {all.Count(h => h.Tier.Tier == t)}"))}");
        var moved = all.Where(h => h.PreviousTier is not null && h.PreviousTier != h.Tier.Tier).ToList();
        if (moved.Count > 0) sb.AppendLine($"- Tier changes vs 4 weeks ago: {string.Join(", ", moved.Select(h => $"{h.Repo.Name} {h.PreviousTier}→{h.Tier.Tier}"))}");
        sb.AppendLine().AppendLine("## Build stability").AppendLine();
        foreach (var h in all.Where(h => h.Weekly.Count >= 2).OrderBy(h => h.Weekly[^1].SuccessRate ?? 1).Take(5))
            sb.AppendLine($"- {h.Repo.Name}: main {Fmt.Pct(h.Weekly[^1].SuccessRate)} this week (was {Fmt.Pct(h.Weekly[^2].SuccessRate)}), red {Fmt.Hours(h.RedWallHours30d)} in 30 d");
        sb.AppendLine().AppendLine("## Flakiness — top wasted minutes").AppendLine();
        foreach (var q in ins.Quarantine.Take(3)) sb.AppendLine($"- {q.RepoName} {q.Stage}/{q.Job}: {q.Occurrences}× flaky, {q.WastedMinutes:0} min wasted");
        if (ins.CrossRepoFailures.Count > 0)
        {
            sb.AppendLine().AppendLine("## Shared failures (likely platform)").AppendLine();
            foreach (var c in ins.CrossRepoFailures.Take(3)) sb.AppendLine($"- {c.Repos} repos / {c.Runs} runs: `{(c.SampleMessage.Length > 120 ? c.SampleMessage[..120] + "…" : c.SampleMessage)}`");
        }
        sb.AppendLine().AppendLine("## PR flow").AppendLine();
        foreach (var h in all.Where(h => h.Prs.FirstReviewHours is not null).OrderByDescending(h => h.Prs.FirstReviewHours).Take(5))
            sb.AppendLine($"- {h.Repo.Name}: first review {h.Prs.FirstReviewHours:0.#} wh ({h.Prs.FirstReviewLabel}), {h.Prs.StuckCount} stuck");
        sb.AppendLine().AppendLine("## Top open audit themes").AppendLine();
        foreach (var t in FindingsService.Themes(backlog).Take(5)) sb.AppendLine($"- {t.CheckId} {t.Title}: {t.Repos} repos");
        return sb.ToString();
    }

    public async Task<string> BriefAsync(CancellationToken ct = default)
    {
        var digest = await DigestAsync(ct);
        var resp = await auditor.TextAsync(new TextTaskRequest
        {
            Kind = "weekly-brief",
            Input = "Write at most 10 short lines for a tech lead's weekly team brief from these week-over-week facts. No names of individuals. Each line should be actionable or informative.\n\n" + digest,
            Model = config.Current.Audit.Model,
        }, ct);
        return resp.Text + $"\n\n— generated by {resp.Engine} {resp.Model}";
    }
}
